validate_email_configuration() {
    if [[ "${ALLOW_EMAIL}" == "true" &&
        ( -z "${EMAIL_SENDER}" || -z "${EMAIL_RECIPIENTS}" ) ]]; then
        printf 'ERROR: enabling email requires sender and recipients\n' >&2
        exit 2
    fi
    [[ -n "${EMAIL_SENDER}" ]] || return 0
    GPU_FAULT_EMAIL_SENDER="${EMAIL_SENDER}" \
        GPU_FAULT_EMAIL_RECIPIENTS="${EMAIL_RECIPIENTS}" \
        python3.12 -c '
import os
import re

pattern = re.compile(r"^[^\s@,]+@[^\s@,]+\.[^\s@,]+$")
sender = os.environ["GPU_FAULT_EMAIL_SENDER"]
recipients = [
    item.strip()
    for item in os.environ["GPU_FAULT_EMAIL_RECIPIENTS"].split(",")
]
if (
    not pattern.fullmatch(sender)
    or not recipients
    or any(not pattern.fullmatch(item) for item in recipients)
):
    raise SystemExit(
        "ERROR: sender or comma-separated recipient email address is invalid"
    )
'
}

load_existing_email_configuration() {
    if [[ "${ALLOW_EMAIL}" != "true" ||
        ( -n "${EMAIL_SENDER}" && -n "${EMAIL_RECIPIENTS}" ) ]]; then
        return
