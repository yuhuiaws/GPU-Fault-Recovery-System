run_e2e() {
    local suffix job attempt retry_job retry_attempt decision plan_id plan
    local workflow_id workflow
    suffix="$(date -u +%H%M%S)"
    job="gpu-fault-e2e-${suffix}"
    attempt="${job}-a1"
    # The runtime profile annotation must name the profile this
    # deployment actually registered (register_runtime_profile posts
    # exactly one, named ${RUNTIME_PROFILE}). Without this rewrite an
    # overridden GPU_FAULT_RUNTIME_PROFILE leaves the manifest default
    # in place, the control plane rejects the watcher's terminal event
    # with 404 "resource not found: <profile>", and because a failed
    # delivery is never added to _terminal_sent the watcher retries it
    # forever while the e2e Job never reaches a decision.
    sed \
        -e "s/gpu-fault-aurora-e2e/${job}/g" \
        -e "s/passive-aurora-e2e-a1/${attempt}/g" \
        -e "s/passive-aurora-e2e/${job}/g" \
        -e "s|\(gpu-fault.io/runtime-profile-version:\).*|\1 ${RUNTIME_PROFILE}|" \
        "${REPO_DIR}/scripts/e2e/manifests/passive-aurora-e2e.yaml" |
        kubectl apply -f -
    kubectl -n "${NAMESPACE}" wait \
        --for=jsonpath='{.spec.suspend}'=true \
        "job/${job}" --timeout=2m
    for _ in {1..60}; do
        retry_job="$(
            kubectl -n "${NAMESPACE}" get jobs -o name |
                sed -n "s|job.batch/${job}-r-|${job}-r-|p" |
                head -n1
        )"
        [[ -n "${retry_job}" ]] && break
        sleep 2
    done
    [[ -n "${retry_job:-}" ]] || {
        printf 'ERROR: retry Job was not created\n' >&2
        exit 1
    }
    kubectl -n "${NAMESPACE}" wait \
        --for=condition=complete "job/${retry_job}" --timeout=3m
    retry_attempt="$(
        kubectl -n "${NAMESPACE}" get pods \
            -l "job-name=${retry_job}" \
            -o jsonpath='{.items[0].metadata.labels.gpu-fault\.io/attempt-id}'
    )"
    decision="$(
        api_python '
import urllib.request
print(urllib.request.urlopen(
  "http://gpu-fault-api-canary:8080/v1/attempts/'"${attempt}"'/decision"
).read().decode())
' | tail -n1
    )"
    plan_id="$(
        VALUE="${decision}" python3.12 -c \
            'import json,os; print(json.loads(os.environ["VALUE"])["recovery_plan_id"])'
    )"
    plan="$(
        api_python '
import urllib.request
print(urllib.request.urlopen(
  "http://gpu-fault-api-canary:8080/v1/recovery-plans/'"${plan_id}"'"
).read().decode())
' | tail -n1
    )"
    workflow_id="$(
        VALUE="${plan}" python3.12 -c \
            'import json,os; print(json.loads(os.environ["VALUE"])["workflow_request_id"])'
    )"
    workflow="$(
        api_python '
import urllib.request
print(urllib.request.urlopen(
  "http://gpu-fault-api-canary:8080/v1/workflows/'"${workflow_id}"'"
).read().decode())
' | tail -n1
    )"
    retry_decision="$(
        api_python '
import urllib.request
print(urllib.request.urlopen(
  "http://gpu-fault-api-canary:8080/v1/attempts/'"${retry_attempt}"'/decision"
).read().decode())
' | tail -n1
    )"
    PLAN="${plan}" WORKFLOW="${workflow}" RETRY="${retry_decision}" \
        python3.12 -c '
import json, os
plan = json.loads(os.environ["PLAN"])
workflow = json.loads(os.environ["WORKFLOW"])
retry = json.loads(os.environ["RETRY"])
assert plan["status"] == "SUCCEEDED", plan
assert workflow["status"] == "SUCCEEDED", workflow
assert len(workflow["official_steps"]) == 1, workflow
assert len(workflow["official_steps"][0]["workload_ids"]) == 1, workflow
assert retry["status"] == "NO_ACTION", retry
assert retry["reason"] == "training attempt succeeded", retry
'
    printf 'PASS E2E: job=%s retry=%s plan=%s workflow=%s\n' \
        "${job}" "${retry_job}" "${plan_id}" "${workflow_id}"
}

