ensure_aurora() {
    local cluster_json vpc_id node_ip node_sg subnet_json
    local subnet_group security_group endpoint secret_arn secret_json url
    local writer_id="${AURORA_CLUSTER_ID}-writer"
    local reader_id="${AURORA_CLUSTER_ID}-reader"

    cluster_json="$(
        aws eks describe-cluster \
            --name "${EKS_CLUSTER_NAME}" \
            --region "${AWS_REGION}" \
            --query cluster.resourcesVpcConfig \
            --output json
    )"
    vpc_id="$(
        CLUSTER_JSON="${cluster_json}" python3.12 -c \
            'import json,os; print(json.loads(os.environ["CLUSTER_JSON"])["vpcId"])'
    )"
    mapfile -t subnet_ids < <(
        CLUSTER_JSON="${cluster_json}" python3.12 -c '
import json, os
for value in json.loads(os.environ["CLUSTER_JSON"])["subnetIds"]:
    print(value)
'
    )
    [[ "${#subnet_ids[@]}" -ge 2 ]] || {
        printf 'ERROR: Aurora requires EKS subnets in at least two AZs\n' >&2
        exit 1
    }
    subnet_json="$(
        aws ec2 describe-subnets \
            --subnet-ids "${subnet_ids[@]}" \
            --region "${AWS_REGION}" \
            --query 'Subnets[].{id:SubnetId,az:AvailabilityZone}' \
            --output json
    )"
    mapfile -t selected_subnets < <(
        SUBNET_JSON="${subnet_json}" python3.12 -c '
import json, os
seen = set()
for item in json.loads(os.environ["SUBNET_JSON"]):
    if item["az"] not in seen:
        print(item["id"])
        seen.add(item["az"])
    if len(seen) == 2:
        break
'
    )
    mapfile -t selected_azs < <(
        SUBNET_JSON="${subnet_json}" python3.12 -c '
import json, os
seen = set()
for item in json.loads(os.environ["SUBNET_JSON"]):
    if item["az"] not in seen:
        print(item["az"])
        seen.add(item["az"])
    if len(seen) == 2:
        break
'
    )
    [[ "${#selected_subnets[@]}" -eq 2 ]] || {
        printf 'ERROR: EKS subnets do not span two AZs\n' >&2
        exit 1
    }

    subnet_group="${AURORA_CLUSTER_ID}"
    if aws rds describe-db-subnet-groups \
        --db-subnet-group-name "${subnet_group}" \
        --region "${AWS_REGION}" >/dev/null 2>&1; then
        aws rds modify-db-subnet-group \
            --db-subnet-group-name "${subnet_group}" \
            --subnet-ids "${selected_subnets[@]}" \
            --region "${AWS_REGION}" >/dev/null
    else
        aws rds create-db-subnet-group \
            --db-subnet-group-name "${subnet_group}" \
            --db-subnet-group-description \
                "GPU fault control plane Aurora private subnets" \
            --subnet-ids "${selected_subnets[@]}" \
            --region "${AWS_REGION}" >/dev/null
    fi

    security_group="$(
        aws ec2 describe-security-groups \
            --filters \
                "Name=vpc-id,Values=${vpc_id}" \
                "Name=group-name,Values=${AURORA_CLUSTER_ID}" \
            --region "${AWS_REGION}" \
            --query 'SecurityGroups[0].GroupId' \
            --output text
    )"
    if [[ "${security_group}" == "None" ]]; then
        security_group="$(
            aws ec2 create-security-group \
                --group-name "${AURORA_CLUSTER_ID}" \
                --description \
                    "Aurora PostgreSQL for GPU fault control plane" \
                --vpc-id "${vpc_id}" \
                --region "${AWS_REGION}" \
                --query GroupId --output text
        )"
    fi
    node_ip="$(
        kubectl get nodes \
            -l "sagemaker.amazonaws.com/cluster-name=${HYPERPOD_CLUSTER_NAME}" \
            -o jsonpath='{.items[0].status.addresses[?(@.type=="InternalIP")].address}'
    )"
    node_sg="$(
        aws ec2 describe-network-interfaces \
            --filters "Name=addresses.private-ip-address,Values=${node_ip}" \
            --region "${AWS_REGION}" \
            --query 'NetworkInterfaces[0].Groups[0].GroupId' \
            --output text
    )"
    if ! aws ec2 authorize-security-group-ingress \
        --group-id "${security_group}" \
        --protocol tcp --port 5432 \
        --source-group "${node_sg}" \
        --region "${AWS_REGION}" >/tmp/gpu-fault-sg.out 2>&1; then
        grep -q InvalidPermission.Duplicate /tmp/gpu-fault-sg.out || {
            cat /tmp/gpu-fault-sg.out >&2
            exit 1
        }
    fi

    if ! aws rds describe-db-clusters \
        --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
        --region "${AWS_REGION}" >/dev/null 2>&1; then
        aws rds create-db-cluster \
            --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
            --engine aurora-postgresql \
            --engine-version "${AURORA_ENGINE_VERSION}" \
            --engine-mode provisioned \
            --database-name gpu_fault \
            --master-username gpu_fault_admin \
            --manage-master-user-password \
            --serverless-v2-scaling-configuration \
                "MinCapacity=${AURORA_MIN_ACU},MaxCapacity=${AURORA_MAX_ACU}" \
            --db-subnet-group-name "${subnet_group}" \
            --vpc-security-group-ids "${security_group}" \
            --storage-encrypted \
            --backup-retention-period 7 \
            --deletion-protection \
            --copy-tags-to-snapshot \
            --enable-iam-database-authentication \
            --tags Key=Application,Value=gpu-fault-control-plane \
            --region "${AWS_REGION}" >/dev/null
    fi
    if ! aws rds describe-db-instances \
        --db-instance-identifier "${writer_id}" \
        --region "${AWS_REGION}" >/dev/null 2>&1; then
        aws rds create-db-instance \
            --db-instance-identifier "${writer_id}" \
            --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
            --engine aurora-postgresql \
            --db-instance-class db.serverless \
            --availability-zone "${selected_azs[0]}" \
            --promotion-tier 0 \
            --region "${AWS_REGION}" >/dev/null
    fi
    if ! aws rds describe-db-instances \
        --db-instance-identifier "${reader_id}" \
        --region "${AWS_REGION}" >/dev/null 2>&1; then
        aws rds create-db-instance \
            --db-instance-identifier "${reader_id}" \
            --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
            --engine aurora-postgresql \
            --db-instance-class db.serverless \
            --availability-zone "${selected_azs[1]}" \
            --promotion-tier 0 \
            --region "${AWS_REGION}" >/dev/null
    fi
    aws rds wait db-instance-available \
        --db-instance-identifier "${writer_id}" \
        --region "${AWS_REGION}"
    aws rds wait db-instance-available \
        --db-instance-identifier "${reader_id}" \
        --region "${AWS_REGION}"

    endpoint="$(
        aws rds describe-db-clusters \
            --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
            --region "${AWS_REGION}" \
            --query 'DBClusters[0].Endpoint' --output text
    )"
    secret_arn="$(
        aws rds describe-db-clusters \
            --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
            --region "${AWS_REGION}" \
            --query 'DBClusters[0].MasterUserSecret.SecretArn' --output text
    )"
    AURORA_MASTER_SECRET_ARN="${secret_arn}"
    # The KMS key lives under RDS's MasterUserSecret, not at the top level of
    # secretsmanager describe-secret, which has no KmsKeyId field at all and
    # would silently yield None.
    AURORA_MASTER_SECRET_KMS_KEY_ARN="$(
        aws rds describe-db-clusters \
            --db-cluster-identifier "${AURORA_CLUSTER_ID}" \
            --region "${AWS_REGION}" \
            --query 'DBClusters[0].MasterUserSecret.KmsKeyId' --output text
    )"
    secret_json="$(
        aws secretsmanager get-secret-value \
            --secret-id "${secret_arn}" \
            --region "${AWS_REGION}" \
            --query SecretString --output text
    )"
    url="$(
        SECRET_JSON="${secret_json}" ENDPOINT="${endpoint}" \
            python3.12 -c '
import json, os
from urllib.parse import quote
s = json.loads(os.environ["SECRET_JSON"])
print(
    "postgresql://"
    + quote(s["username"], safe="")
    + ":"
    + quote(s["password"], safe="")
    + "@"
    + os.environ["ENDPOINT"]
    + ":5432/gpu_fault?sslmode=require"
)
'
    )"
    kubectl -n "${NAMESPACE}" create secret generic gpu-fault-aurora \
        --from-literal=postgres-url="${url}" \
        --from-literal=master-secret-arn="${secret_arn}" \
        --dry-run=client -o yaml | kubectl apply -f -
}

