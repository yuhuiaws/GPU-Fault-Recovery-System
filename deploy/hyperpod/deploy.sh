        kubectl -n "${NAMESPACE}" create secret generic \
            gpu-fault-control-plane-active \
            --from-literal=execution-token="$(openssl rand -hex 32)" \
            --from-literal=node-action-secret="$(openssl rand -hex 32)" \
            --from-literal=processor-replay-secret="$(
                openssl rand -hex 32
            )"
    elif [[ -z "$(
        kubectl -n "${NAMESPACE}" get secret \
            gpu-fault-control-plane-active \
            -o jsonpath='{.data.processor-replay-secret}'
    )" ]]; then
        replay_secret="$(
            printf '%s' "$(openssl rand -hex 32)" | base64 -w0
        )"
        kubectl -n "${NAMESPACE}" patch secret \
            gpu-fault-control-plane-active \
            --type merge \
            -p "{\"data\":{\"processor-replay-secret\":\"${replay_secret}\"}}" \
            >/dev/null
        unset replay_secret
    fi
}

