    EMAIL_SENDER="$(
        kubectl -n "${NAMESPACE}" get secret \
            "${EMAIL_SECRET_NAME}" \
            -o jsonpath='{.data.email-sender}' | base64 -d
    )"
    EMAIL_RECIPIENTS="$(
        kubectl -n "${NAMESPACE}" get secret \
            "${EMAIL_SECRET_NAME}" \
            -o jsonpath='{.data.email-recipients}' | base64 -d
    )"
}

