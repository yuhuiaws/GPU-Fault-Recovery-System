                  url="\$(printf "%s" "\${METRICS_URL_B64}" | base64 -d)"
                  if output="\$(curl --fail --silent --show-error \
                      --connect-timeout 3 --max-time 10 \
                      "\${url}")"; then
                    missing=""
                    IFS="," read -ra fields <<< "\${REQUIRED_METRICS}"
                    for requirement in "\${fields[@]}"; do
                      found=false
                      IFS="|" read -ra alternatives <<< "\${requirement}"
                      for field in "\${alternatives[@]}"; do
                        if grep -Eq "^\${field}(_total)?(\\{| )" \
                            <<< "\${output}"; then
                          found=true
                          break
                        fi
                      done
                      if [[ "\${found}" != "true" ]]; then
                        missing="\${missing:+\${missing},}\${requirement}"
                      fi
                    done
                    if [[ -z "\${missing}" ]]; then
                      printf "COMPATIBLE\n"
                    else
                      printf "INCOMPATIBLE missing=%s\n" "\${missing}"
                    fi
                  elif [[ "\${CHECK_MANAGED_PORT}" == "true" ]] &&
                      timeout 2 bash -c "</dev/tcp/127.0.0.1/9400" \
                          >/dev/null 2>&1; then
                    printf "OCCUPIED port=9400\n"
                  else
                    printf "ABSENT\n"
                  fi
                '
          volumeMounts:
            - name: host-root
              mountPath: /host
              readOnly: true
      volumes:
        - name: host-root
          hostPath:
            path: /
            type: Directory
EOF
    if ! kubectl -n "${NAMESPACE}" wait \
        --for=condition=complete "job/${job_name}" --timeout=2m \
        >/dev/null; then
        kubectl -n "${NAMESPACE}" logs "job/${job_name}" \
            --all-containers >&2 || true
        printf 'ERROR: DCGM endpoint probe failed on %s\n' "${node}" >&2
        return 1
    fi
    result="$(
        kubectl -n "${NAMESPACE}" logs "job/${job_name}" \
            --all-containers | tail -n1
    )"
    kubectl -n "${NAMESPACE}" delete job "${job_name}" \
        --ignore-not-found --wait=false >/dev/null
    printf '%s\n' "${result}"
}

probe_dcgm_nodes() {
    local check_managed_port="$1" node node_ip metrics_url result
    local compatible=0 absent=0 incompatible=0 total=0
    mapfile -t dcgm_nodes < <(
        kubectl get nodes \
            -l "sagemaker.amazonaws.com/cluster-name=${HYPERPOD_CLUSTER_NAME}" \
            -o jsonpath='{range .items[*]}{.metadata.name}{"\n"}{end}'
    )
    [[ "${#dcgm_nodes[@]}" -gt 0 ]] || {
        printf 'ERROR: no HyperPod nodes discovered for DCGM probe\n' >&2
        return 1
    }
    for node in "${dcgm_nodes[@]}"; do
        node_ip="$(
            kubectl get node "${node}" \
                -o jsonpath='{.status.addresses[?(@.type=="InternalIP")].address}'
        )"
        metrics_url="$(render_dcgm_metrics_url "${node}" "${node_ip}")"
        result="$(
            probe_dcgm_node \
                "${node}" "${metrics_url}" "${check_managed_port}"
        )"
        printf 'DCGM probe node=%s endpoint=%s result=%s\n' \
            "${node}" "${metrics_url}" "${result}" >&2
        total=$((total + 1))
        case "${result}" in
            COMPATIBLE) compatible=$((compatible + 1)) ;;
            ABSENT) absent=$((absent + 1)) ;;
            *) incompatible=$((incompatible + 1)) ;;
        esac
    done
    if (( compatible == total )); then
        printf 'COMPATIBLE\n'
    elif (( absent == total )); then
        printf 'ABSENT\n'
    else
        printf 'MIXED compatible=%d absent=%d incompatible=%d\n' \
            "${compatible}" "${absent}" "${incompatible}"
    fi
}

resolve_dcgm_exporter_mode() {
    local result original_template="${DCGM_METRICS_URL_TEMPLATE}"
    [[ -z "${RESOLVED_DCGM_EXPORTER_MODE}" ]] || return 0
    if [[ "${DCGM_EXPORTER_MODE}" == "disabled" ]]; then
        RESOLVED_DCGM_EXPORTER_MODE="disabled"
        return 0
    fi
    if kubectl -n "${NAMESPACE}" get daemonset \
        gpu-fault-dcgm-exporter >/dev/null 2>&1; then
        if [[ "${DCGM_EXPORTER_MODE}" == "existing" ]]; then
            if [[ "${DCGM_METRICS_URL_TEMPLATE}" == \
                "http://127.0.0.1:9400/metrics" ]]; then
                printf 'ERROR: existing mode cannot reuse this solution-owned exporter; configure the external endpoint URL first\n' >&2
                return 1
            fi
        else
            RESOLVED_DCGM_EXPORTER_MODE="managed"
            DCGM_METRICS_URL_TEMPLATE="http://127.0.0.1:9400/metrics"
            return 0
        fi
    fi
    if [[ "${DCGM_EXPORTER_MODE}" == "managed" ]]; then
        DCGM_METRICS_URL_TEMPLATE="http://127.0.0.1:9400/metrics"
        result="$(probe_dcgm_nodes true)"
        [[ "${result}" == "ABSENT" ]] || {
            printf 'ERROR: managed DCGM exporter requires free port 9400 on every node; probe=%s\n' \
                "${result}" >&2
            return 1
        }
        RESOLVED_DCGM_EXPORTER_MODE="managed"
        return 0
    fi
    result="$(probe_dcgm_nodes false)"
    case "${DCGM_EXPORTER_MODE}:${result}" in
        existing:COMPATIBLE|auto:COMPATIBLE)
            RESOLVED_DCGM_EXPORTER_MODE="existing"
            ;;
        auto:ABSENT)
            DCGM_METRICS_URL_TEMPLATE="http://127.0.0.1:9400/metrics"
            result="$(probe_dcgm_nodes true)"
            [[ "${result}" == "ABSENT" ]] || {
                printf 'ERROR: port 9400 is not available for managed fallback; probe=%s\n' \
                    "${result}" >&2
                return 1
            }
            RESOLVED_DCGM_EXPORTER_MODE="managed"
            ;;
        *)
            DCGM_METRICS_URL_TEMPLATE="${original_template}"
            printf 'ERROR: DCGM exporter mode %s cannot use node endpoints; probe=%s\n' \
                "${DCGM_EXPORTER_MODE}" "${result}" >&2
            return 1
            ;;
    esac
    printf 'Resolved DCGM exporter mode: requested=%s resolved=%s url=%s\n' \
        "${DCGM_EXPORTER_MODE}" "${RESOLVED_DCGM_EXPORTER_MODE}" \
        "${DCGM_METRICS_URL_TEMPLATE}"
}

configure_dcgm_exporter() {
    resolve_dcgm_exporter_mode
    if [[ "${RESOLVED_DCGM_EXPORTER_MODE}" != "managed" ]]; then
        kubectl -n "${NAMESPACE}" delete daemonset \
            gpu-fault-dcgm-exporter --ignore-not-found
        return 0
    fi
    sed \
        "s#${DEFAULT_DCGM_EXPORTER_IMAGE}#${DCGM_EXPORTER_IMAGE}#g" \
        "${REPO_DIR}/deploy/dataplane/hyperpod-dcgm-exporter.yaml" |
        kubectl apply -f -
    local instance_type
    instance_type="$(
        kubectl get nodes \
            -l "sagemaker.amazonaws.com/cluster-name=${HYPERPOD_CLUSTER_NAME}" \
            -o jsonpath='{.items[0].metadata.labels.node\.kubernetes\.io/instance-type}'
    )"
    kubectl -n "${NAMESPACE}" patch daemonset \
        gpu-fault-dcgm-exporter --type=merge \
        -p "{\"spec\":{\"template\":{\"spec\":{\"nodeSelector\":{\"node.kubernetes.io/instance-type\":\"${instance_type}\",\"sagemaker.amazonaws.com/cluster-name\":\"${HYPERPOD_CLUSTER_NAME}\"}}}}}"
    # dcgm-exporter reads the collectors CSV only at process startup.
    kubectl -n "${NAMESPACE}" rollout restart \
        daemonset/gpu-fault-dcgm-exporter
    kubectl -n "${NAMESPACE}" rollout status \
        daemonset/gpu-fault-dcgm-exporter --timeout=10m
    local probe_result
    probe_result="$(probe_dcgm_nodes false)"
    [[ "${probe_result}" == "COMPATIBLE" ]] || {
        printf 'ERROR: managed DCGM exporter lacks required metrics; probe=%s\n' \
            "${probe_result}" >&2
        return 1
    }
}

deploy_aurora_credential_refresh() {
    # RDS rotates the managed master password on a schedule (7 days by
    # default), but ensure_aurora only snapshots the password of the moment
    # into the gpu-fault-aurora Secret. Without this CronJob the control plane
    # keeps running on the stale password until something restarts a pod, then
    # every replica CrashLoopBackOffs. See GF-REGIONAL-BOOT-016 附带发现 2.
    local account_id issuer issuer_host role_name trust policy
    [[ -n "${AURORA_MASTER_SECRET_ARN}" ]] || {
        printf 'ERROR: AURORA_MASTER_SECRET_ARN is unset\n' >&2
        return 1
    }
    account_id="$(aws sts get-caller-identity --query Account --output text)"
    issuer="$(
        aws eks describe-cluster \
            --name "${EKS_CLUSTER_NAME}" \
            --region "${AWS_REGION}" \
            --query cluster.identity.oidc.issuer \
            --output text
    )"
    [[ "${issuer}" == https://* ]] || {
        printf 'ERROR: EKS cluster has no IAM OIDC issuer\n' >&2
        return 1
    }
    issuer_host="${issuer#https://}"
    role_name="${AURORA_REFRESH_ROLE_NAME}"
    role_name="${role_name:0:64}"
    trust="$(
        ACCOUNT_ID="${account_id}" ISSUER="${issuer_host}" \
            NAMESPACE="${NAMESPACE}" python3.12 -c '
import json, os
issuer = os.environ["ISSUER"]
print(json.dumps({
    "Version": "2012-10-17",
    "Statement": [{
        "Effect": "Allow",
        "Principal": {
            "Federated": (
                "arn:aws:iam::" + os.environ["ACCOUNT_ID"]
                + ":oidc-provider/" + issuer
            )
        },
        "Action": "sts:AssumeRoleWithWebIdentity",
        "Condition": {
            "StringEquals": {
                issuer + ":aud": "sts.amazonaws.com",
                issuer + ":sub": (
                    "system:serviceaccount:"
                    + os.environ["NAMESPACE"]
                    + ":gpu-fault-aurora-credential-refresh"
                ),
            }
        },
    }],
}))
'
    )"
    if ! aws iam get-role --role-name "${role_name}" >/dev/null 2>&1; then
        aws iam create-role \
            --role-name "${role_name}" \
            --assume-role-policy-document "${trust}" >/dev/null
    fi
    policy="$(
        SECRET_ARN="${AURORA_MASTER_SECRET_ARN}" \
            KMS_KEY_ARN="${AURORA_MASTER_SECRET_KMS_KEY_ARN}" \
            python3.12 -c '
import json, os
statements = [
    {
        "Sid": "ReadAuroraManagedMasterSecret",
        "Effect": "Allow",
        "Action": ["secretsmanager:GetSecretValue"],
        "Resource": os.environ["SECRET_ARN"],
    },
]
if os.environ["KMS_KEY_ARN"] not in {"", "None"}:
    statements.append({
        "Sid": "DecryptAuroraManagedMasterSecret",
        "Effect": "Allow",
        "Action": ["kms:Decrypt"],
        "Resource": os.environ["KMS_KEY_ARN"],
    })
print(json.dumps({
    "Version": "2012-10-17",
    "Statement": statements,
}))
'
    )"
    aws iam put-role-policy \
        --role-name "${role_name}" \
        --policy-name ReadAuroraManagedMasterSecret \
        --policy-document "${policy}"
    # No region substitution: EKS injects AWS_REGION into the pod.
    sed \
        -e "s/gpu-fault-control-plane-wheel-0100/${WHEEL_CONFIGMAP_NAME}/g" \
        -e "s#${DEFAULT_RUNTIME_IMAGE}#${RUNTIME_IMAGE}#g" \
        -e "s#REPLACE_WITH_AURORA_MASTER_SECRET_ARN#${AURORA_MASTER_SECRET_ARN}#g" \
        "${REPO_DIR}/deploy/control-plane/regional/aurora-credential-refresh.yaml" |
        kubectl apply -f -
    kubectl -n "${NAMESPACE}" annotate serviceaccount \
        gpu-fault-aurora-credential-refresh \
        "eks.amazonaws.com/role-arn=arn:aws:iam::${account_id}:role/${role_name}" \
        --overwrite
    # Prove the credentials and RBAC work now, rather than discovering it at
    # the next rotation. The password has not changed, so the expected result
    # is the no-op path: no Secret write and no restart.
    kubectl -n "${NAMESPACE}" delete job \
        gpu-fault-aurora-credential-refresh-verify \
        --ignore-not-found >/dev/null
    kubectl -n "${NAMESPACE}" create job \
        gpu-fault-aurora-credential-refresh-verify \
        --from=cronjob/gpu-fault-aurora-credential-refresh >/dev/null
    if ! kubectl -n "${NAMESPACE}" wait \
        --for=condition=complete \
        job/gpu-fault-aurora-credential-refresh-verify \
        --timeout=420s; then
        printf 'ERROR: aurora credential refresh verification failed\n' >&2
        kubectl -n "${NAMESPACE}" logs \
            job/gpu-fault-aurora-credential-refresh-verify | tail -20 >&2
        return 1
    fi
    kubectl -n "${NAMESPACE}" logs \
        job/gpu-fault-aurora-credential-refresh-verify |
        grep 'aurora credential refresh:'
    kubectl -n "${NAMESPACE}" delete job \
        gpu-fault-aurora-credential-refresh-verify >/dev/null
}

