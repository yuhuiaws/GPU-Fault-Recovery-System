    job_name="${job_name:0:63}"
    url_b64="$(printf '%s' "${metrics_url}" | base64 | tr -d '\n')"
    kubectl -n "${NAMESPACE}" delete job "${job_name}" \
        --ignore-not-found --wait=true >/dev/null
    kubectl apply -f - >/dev/null <<EOF
